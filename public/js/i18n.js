  function getTimeGreeting(lang, detailed) {
    const h = new Date().getHours();
    if (lang === 'id') {
      if (h >= 4 && h < 11) return detailed ? 'Selamat pagi! Siap cek kualitas udara hari ini?' : 'Selamat pagi!';
      if (h >= 11 && h < 15) return detailed ? 'Halo! Selamat siang.' : 'Halo, Selamat siang!';
      if (h >= 15 && h < 18) return detailed ? 'Hai! Selamat sore.' : 'Hai, Selamat sore!';
      return detailed ? 'Selamat malam! Siap cek prakiraan esok hari?' : 'Selamat malam!';
    }
    if (h >= 4 && h < 11) return detailed ? 'Good morning!' : 'Good morning!';
    if (h >= 11 && h < 15) return detailed ? 'Hello! Good afternoon.' : 'Hello!';
    if (h >= 15 && h < 18) return detailed ? 'Hi there! Good afternoon.' : 'Hi!';
    return detailed ? 'Good evening!' : 'Good evening!';
  }

  window.NafasI18n = {
    getLang: function () {
      const saved = window.NafasState ? window.NafasState.get().lang : 'en';
      return saved === 'id' ? 'id' : 'en';
    },
    t: function (key) {
      const lang = this.getLang();
      if (key === 'dash_greeting') return getTimeGreeting(lang, true);
      if (key === 'role_title') return getTimeGreeting(lang, false);
      return (DICT[lang] && DICT[lang][key]) || DICT.en[key] || key;
    },
    apply: function () {
      const self = this;
      $('[data-i18n]').each(function () {
        const key = $(this).attr('data-i18n');
        $(this).text(self.t(key));
      });
      $('[data-i18n-placeholder]').each(function () {
        const key = $(this).attr('data-i18n-placeholder');
        $(this).attr('placeholder', self.t(key));
      });
      document.documentElement.lang = self.getLang();
    }
  };
